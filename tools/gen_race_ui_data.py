#!/usr/bin/env python3
"""Extract the six-language race UI tables used by 0x21d68/0x21448/0x4395c/0x43fe0."""
import argparse
from pathlib import Path

from gen_menu_data import Mem, c_string
from disasm import DEFAULT_EXE

TABLES = [
    ("track", 0xC0C68, 105, 15, 7),
    ("pause", 0xC0EDE, 210, 30, 7),
    ("quit", 0xC13CA, 30, 30, 1),
    ("restart", 0xC147E, 30, 30, 1),
    ("loading", 0xC1532, 30, 30, 1),
    ("results", 0xC15E6, 30, 30, 1),
    ("track_score", 0xC169A, 30, 30, 1),
    ("total_score", 0xC174E, 30, 30, 1),
    ("again", 0xC1802, 45, 45, 1),
    ("continue", 0xC19C4, 50, 50, 1),
    ("network", 0xC1D48, 150, 50, 3),
    ("complete", 0xC20CC, 100, 100, 1),
    ("advance", 0xC2324, 100, 100, 1),
    ("failed", 0xC257C, 100, 50, 2),
]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--exe", default=DEFAULT_EXE)
    parser.add_argument("-o", type=Path, default=Path("src/frontend/race_ui_data.h"))
    args = parser.parse_args()
    mem = Mem(args.exe)
    lines = ["/* Generated by tools/gen_race_ui_data.py from the original language tables. */",
             "#ifndef IGN_RACE_UI_DATA_H", "#define IGN_RACE_UI_DATA_H", ""]
    for name, base, stride, item_stride, count in TABLES:
        lines.append(f"static const char *const race_text_{name}[6][{count}] = {{")
        for language in range(6):
            strings = [c_string(mem.cstr(base + language * stride + i * item_stride)) for i in range(count)]
            if "NULL" in strings:
                raise ValueError(f"Missing {name} table in language {language}")
            lines.append("    {" + ", ".join(strings) + "},")
        lines.append("};")
    lines += ["", "#endif", ""]
    args.o.write_text("\n".join(lines), encoding="ascii")


if __name__ == "__main__":
    main()
